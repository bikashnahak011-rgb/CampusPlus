export function normalizeLanguage(language) {
  const candidate = typeof language === 'string' ? language.trim().toLowerCase() : 'en'
  return Object.prototype.hasOwnProperty.call(translations, candidate) ? candidate : 'en'
}

export function translateText(language, key, fallback = '', params) {
  const normalized = normalizeLanguage(language)
  const entries = translations[normalized] || translations.en
  const baseValue = entries[key] ?? translations.en[key] ?? (typeof fallback === 'string' ? fallback : key)
  const interpolationValues = params ?? (typeof fallback === 'object' && fallback !== null ? fallback : {})

  if (typeof baseValue !== 'string') return baseValue
  if (!interpolationValues || typeof interpolationValues !== 'object') return baseValue

  return Object.entries(interpolationValues).reduce(
    (result, [token, value]) => result.replaceAll(`{${token}}`, String(value)),
    baseValue
  )
}
